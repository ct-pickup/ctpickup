#!/usr/bin/env node
// DEV ONLY. Geocodes three hand-added indoor venues with the free US Census geocoder and writes the SQL to add them.
//
//   node scripts/dev/geocode-indoor-venues.mjs            writes scripts/dev/fields_indoor_venues.sql
//
// This script only calls the Census geocoder (no key, no cost). It never connects to a database: you review the SQL it writes,
// then paste it into the DEV Supabase SQL Editor. Needs migration 20261019000000_venues_source_manual.sql applied first.
// A venue the geocoder cannot match is left out (no guessed coordinates) and the script exits with code 2.

import { writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";

const CENSUS = "https://geocoding.geo.census.gov/geocoder/locations/onelineaddress";

/** Address candidates are tried in order; the first the Census geocoder matches wins. */
export const VENUES = [
  {
    key: "manual-socceroof-wall-street",
    name: "Socceroof Wall Street",
    state: "NY",
    address: "28 Liberty St, Lower Level 1, New York, NY 10005",
    candidates: ["28 Liberty St, New York, NY 10005"],
    price: { status: "paid", min: 130, max: 500, unit: "hour", text: "From $130/hr (small field) to $500/hr (big field), 2-hour minimum. Source: Tagvenue listing, unconfirmed." },
    notes: "Price from a Tagvenue listing, unconfirmed.",
  },
  {
    key: "manual-socceroof-long-island-city",
    name: "Socceroof Long Island City",
    state: "NY",
    address: "36-39 35th Street, Long Island City, NY",
    candidates: ["36-39 35th Street, Long Island City, NY", "36-39 35th Street, Long Island City, NY 11106"],
    price: null,
    notes: null,
  },
  {
    key: "manual-socceroof-new-rochelle",
    name: "Socceroof New Rochelle",
    state: "NY",
    address: "3rd floor, New Roc Mall, New Rochelle, NY",
    // The mall has no street number in the brief, and the Census geocoder cannot match a mall name. The street address below is
    // the mall's (New Roc City, 33 Le Count Pl): check the matched address this script prints before you run the SQL.
    candidates: ["33 Le Count Pl, New Rochelle, NY 10801", "33 Le Count Pl, New Rochelle, NY"],
    price: null,
    notes: null,
  },
];

const LOCKED = ["name", "lat", "lon", "setting", "surface", "lit", "address", "website"];

export function q(s) {
  return s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`;
}

/** @param {{v: typeof VENUES[number], lat: number, lon: number}[]} rows */
export function buildSql(rows) {
  const out = [];
  out.push("-- DEV ONLY. Generated by scripts/dev/geocode-indoor-venues.mjs. Never run this on production.");
  out.push("-- Needs migration 20261019000000_venues_source_manual.sql. Safe to run more than once.");
  out.push("begin;", "");
  for (const { v, lat, lon } of rows) {
    const p = v.price;
    out.push(`insert into public.venues (
  venue_key, state, name, lat, lon, venue_type, access, address, setting, sport_confidence, priority,
  price_status, price_text, price_min, price_max, price_unit, price_source,
  booking_method, booking_basis, permit_required,
  verified, source, locked_fields, player_notes, updated_at
) values (
  ${q(v.key)}, ${q(v.state)}, ${q(v.name)}, ${lat}, ${lon}, 'club', 'unknown', ${q(v.address)}, 'indoor', 'manual', 1,
  ${q(p ? p.status : "unknown")}, ${q(p?.text ?? null)}, ${p ? p.min : "null"}, ${p ? p.max : "null"}, ${q(p?.unit ?? null)}, 'unknown',
  'unknown', 'Book through the venue.', 'unknown',
  false, 'manual', array[${LOCKED.map(q).join(", ")}], ${q(v.notes)}, now()
)
on conflict (venue_key) do update set
  state = excluded.state, name = excluded.name, lat = excluded.lat, lon = excluded.lon, address = excluded.address,
  setting = 'indoor', price_status = excluded.price_status, price_text = excluded.price_text, price_min = excluded.price_min,
  price_max = excluded.price_max, price_unit = excluded.price_unit, price_source = 'unknown',
  booking_basis = excluded.booking_basis, verified = false, source = 'manual', locked_fields = excluded.locked_fields,
  player_notes = excluded.player_notes, updated_at = now();
`);
  }
  out.push(`-- The existing Socceroof in Crown Heights (1700 Atlantic Avenue) becomes indoor, and "setting" is locked so a re-import keeps it.
-- Stops with an error (and changes nothing) unless exactly one venue matches.
do $$
declare n integer;
begin
  select count(*) into n from public.venues
  where name ilike 'socceroof%' and venue_key not like 'manual-%'
    and (address ilike '%1700 Atlantic%' or (lat between 40.667 and 40.688 and lon between -73.946 and -73.926));
  if n <> 1 then
    raise exception 'Expected exactly one Crown Heights Socceroof, found %. Nothing was changed.', n;
  end if;
  update public.venues
  set setting = 'indoor',
      locked_fields = (select array(select distinct unnest(coalesce(locked_fields, '{}') || array['setting']))),
      updated_at = now()
  where name ilike 'socceroof%' and venue_key not like 'manual-%'
    and (address ilike '%1700 Atlantic%' or (lat between 40.667 and 40.688 and lon between -73.946 and -73.926));
end $$;
`);
  out.push("commit;", "", "-- Check:", "-- select venue_key, name, setting, source, verified, price_source, price_text, lat, lon, locked_fields from public.venues", "-- where venue_key like 'manual-socceroof%' or name ilike 'socceroof%';");
  return out.join("\n") + "\n";
}

async function geocode(address) {
  const url = `${CENSUS}?address=${encodeURIComponent(address)}&benchmark=Public_AR_Current&format=json`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`Census geocoder answered ${res.status}`);
  const json = await res.json();
  const m = json?.result?.addressMatches?.[0];
  return m ? { lat: Number(m.coordinates.y), lon: Number(m.coordinates.x), matched: String(m.matchedAddress) } : null;
}

async function main() {
  const rows = [];
  let missed = 0;
  for (const v of VENUES) {
    let hit = null;
    for (const c of v.candidates) {
      hit = await geocode(c);
      if (hit) break;
    }
    if (!hit) {
      console.error(`NO MATCH  ${v.name}: left out (tried ${v.candidates.join(" | ")})`);
      missed++;
      continue;
    }
    console.log(`OK  ${v.name}: ${hit.matched}  ->  ${hit.lat}, ${hit.lon}`);
    rows.push({ v, lat: Number(hit.lat.toFixed(6)), lon: Number(hit.lon.toFixed(6)) });
  }
  const file = fileURLToPath(new URL("./fields_indoor_venues.sql", import.meta.url));
  writeFileSync(file, buildSql(rows));
  console.log(`Wrote ${file} (${rows.length} of ${VENUES.length} venues).`);
  if (missed) process.exit(2);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((e) => {
    console.error(e instanceof Error ? e.message : e);
    process.exit(1);
  });
}
