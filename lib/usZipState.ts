/**
 * @param zip5 — exactly five digits (caller may strip non-digits first).
 * @returns two-letter state/territory code, or `null` if unknown / invalid.
 */
export function stateFromUsZipFive(zip5: string): string | null {
  const zip = zip5.slice(0, 5);
  if (!/^\d{5}$/.test(zip)) return null;

  const exceptionIdx = ZIP_EXCEPTION_REGION_INDEX[zip];
  const regionIndex =
    exceptionIdx !== undefined ? exceptionIdx : PREFIX_TO_REGION_INDEX[Number.parseInt(zip.slice(0, 3), 10)];

  const code = REGION_CODES[regionIndex];
  return code ?? null;
}
